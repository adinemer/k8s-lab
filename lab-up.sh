#!/usr/bin/env bash
# lab-up.sh - create the lab VMs from the spec, each with a cloud-init seed.
#   ./lab-up.sh              create every node in lab.yaml
#   ./lab-up.sh cp2          create only cp2
#   ./lab-up.sh --spec kthw.yaml   use another spec file
# A VM that already exists is skipped, so running it twice is safe.

source "$(dirname "$0")/lib.sh"

usage() { sed -n '2,6p' "$0"; }
parse_args "$@"

# Values from the spec (or sensible defaults).
NET_NAME="$(net_get name)"
GATEWAY="$(net_get gateway)"
DOMAIN="$(net_get domain)"
CIDR="$(net_get cidr)"
PREFIX="${CIDR#*/}"                       # "192.168.150.0/24" -> "24"
IMAGE="$(top_get image)"
IMAGE="${IMAGE:-/var/lib/libvirt/images/ubuntu-26.04-server-cloudimg-amd64.img}"
PUBKEY_FILE="${SSH_PUBKEY:-$HOME/.ssh/id_ed25519.pub}"
OSINFO="${OSINFO:-ubuntu24.04}"           # only tunes virtual hardware defaults

[[ -n "$NET_NAME" && -n "$GATEWAY" && -n "$PREFIX" ]] || die "network section incomplete in $SPEC"
sudo test -f "$IMAGE" || die "base image not found: $IMAGE"
[[ -f "$PUBKEY_FILE" ]] || die "SSH public key not found: $PUBKEY_FILE (set SSH_PUBKEY=...)"
PUBKEY="$(cat "$PUBKEY_FILE")"
command -v xorrisofs >/dev/null || die "xorrisofs not found; install it with: sudo dnf install xorriso"

sudo mkdir -p "$DISK_DIR"
SEED_TMP="$(mktemp -d)"
trap 'rm -rf "$SEED_TMP"' EXIT

NODES="$(selected_nodes)"              # stops here if a name is wrong
while read -r NAME IP VCPU RAM_GIB DISK_GIB; do
  if vm_exists "$NAME"; then
    say "$NAME already exists, skipping"
    continue
  fi
  say "creating $NAME ($IP, ${VCPU} vCPU, ${RAM_GIB} GiB RAM, ${DISK_GIB} GiB disk)"

  # 1. Disk: a copy-on-write layer on top of the shared base image.
  DISK="$DISK_DIR/$NAME.qcow2"
  sudo qemu-img create -q -f qcow2 -F qcow2 -b "$IMAGE" "$DISK" "${DISK_GIB}G"

  # 2. cloud-init seed: who the VM is (meta-data), what to set up (user-data),
  #    and its fixed address (network-config).
  mkdir -p "$SEED_TMP/$NAME"
  cat > "$SEED_TMP/$NAME/meta-data" <<EOF
instance-id: $NAME
local-hostname: $NAME
EOF
  cat > "$SEED_TMP/$NAME/user-data" <<EOF
#cloud-config
hostname: $NAME
fqdn: $NAME.$DOMAIN
manage_etc_hosts: true
ssh_authorized_keys:
  - $PUBKEY
EOF
  cat > "$SEED_TMP/$NAME/network-config" <<EOF
version: 2
ethernets:
  primary:
    match:
      name: "en*"
    addresses: [$IP/$PREFIX]
    routes:
      - to: default
        via: $GATEWAY
    nameservers:
      addresses: [$GATEWAY]
      search: [$DOMAIN]
EOF

  # The three files go on a small CD image labelled "cidata": the NoCloud
  # datasource looks for that label. It is kept beside the disk (not deleted)
  # so snapshots that include the CD drive can always be reverted.
  SEED="$DISK_DIR/$NAME-seed.iso"
  xorrisofs -quiet -output "$SEED_TMP/$NAME-seed.iso" -volid cidata -joliet -rock \
    "$SEED_TMP/$NAME/meta-data" "$SEED_TMP/$NAME/user-data" "$SEED_TMP/$NAME/network-config"
  sudo install -m 0644 "$SEED_TMP/$NAME-seed.iso" "$SEED"

  # 3. The VM itself. --import boots the existing disk instead of an installer.
  sudo virt-install --connect qemu:///system \
    --name "$NAME" \
    --memory $((RAM_GIB * 1024)) --vcpus "$VCPU" \
    --disk "path=$DISK,format=qcow2,bus=virtio" \
    --disk "path=$SEED,device=cdrom" \
    --network "network=$NET_NAME,model=virtio" \
    --osinfo "$OSINFO" \
    --import --graphics none --noautoconsole \
    >/dev/null
done <<< "$NODES"

# 4. SSH by hostname: write an ssh config for every node in the spec.
SSH_CONFIG="$LAB_DIR/ssh-config"
{
  echo "# Generated by lab-up.sh from $(basename "$SPEC"). Lab VMs are rebuilt often,"
  echo "# so host keys are not stored or checked."
  while read -r NAME IP _; do
    echo "Host $NAME $NAME.$DOMAIN"
    echo "  HostName $IP"
    echo "  User ubuntu"
    echo "  StrictHostKeyChecking no"
    echo "  UserKnownHostsFile /dev/null"
    echo "  LogLevel ERROR"
  done < <(all_nodes)
} > "$SSH_CONFIG"

say "done. VMs need about a minute to boot. Then: ssh cp1"
grep -q "Include $SSH_CONFIG" "$HOME/.ssh/config" 2>/dev/null ||
  say "one-time setup: add this as the FIRST line of ~/.ssh/config:  Include $SSH_CONFIG"
